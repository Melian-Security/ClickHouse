SELECT
    id,
    ts,
    event,
    toJSONString(event) AS raw,
    map('org_id', (id % 13)::Dynamic, 'pipeline', concat('p', toString(id % 5))::Dynamic, 'received_at', (ts + id % 3)::Dynamic,
        'size', length(raw)::Dynamic, 'tenant', event.metadata.tenant_uid::Dynamic) AS internal_tags,
    event.message AS message,
    event.metadata.uid AS uid,
    event.device.hostname AS device_hostname,
    event.type_name AS type_name,
    event.actor.user.name AS actor_user_name,
    event.process.cmd_line AS process_cmd_line,
    ifNull(event.src_endpoint.ip, '') AS src_endpoint_ip,
    event.actor.user.uid AS actor_user_uid,
    event.src_endpoint.port AS src_endpoint_port,
    event.type_uid AS type_uid,
    event.activity_name AS activity_name,
    event.class_name AS class_name,
    ts + id % 7 AS insertion_time,
    event.category_name AS category_name,
    event.metadata.product.name AS product_name,
    event.class_uid AS class_uid,
    ifNull(event.dst_endpoint.ip, '') AS dst_endpoint_ip,
    ts + 1 AS ingestion_time,
    event.category_uid AS category_uid,
    event.metadata.product.vendor_name AS product_vendor_name,
    event.activity_id AS activity_id,
    event.dst_endpoint.port AS dst_endpoint_port,
    event.status AS status,
    event.severity AS severity,
    concat(event.metadata.product.name, '-', toString(event.class_uid)) AS log_source
